// A minimal ZIP writer for building test packages, including deliberately hostile ones. It is test
// code: it writes whatever it is told, lying headers included.
import { crc32 } from "../src/zip.ts";

/** One entry to write. */
export interface ZipEntrySpec {
  path: string;
  content: Uint8Array | string;
  /** Defaults to `deflate`. */
  method?: "store" | "deflate";
  /** Marks the entry as a Unix symbolic link; its content is the link target. */
  symlink?: boolean;
  /** Overrides the uncompressed size written in both headers, to build an archive that lies. */
  declaredSize?: number;
}

const encoder = new TextEncoder();
// 2026-10-01 00:00, so generated bytes do not depend on when they were built.
const DOS_DATE = ((2026 - 1980) << 9) | (10 << 5) | 1;
const DOS_TIME = 0;
const UNIX_MADE_BY = (3 << 8) | 20;

/** Raw-deflates `bytes` with the platform's `CompressionStream`. */
export async function deflateRaw(bytes: Uint8Array): Promise<Uint8Array> {
  const stream = new Blob([bytes]).stream().pipeThrough(new CompressionStream("deflate-raw"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** Writes `entries`, in order, as a ZIP archive. */
export async function buildZip(entries: readonly ZipEntrySpec[]): Promise<Uint8Array> {
  const locals: Uint8Array[] = [];
  const centrals: Uint8Array[] = [];
  let offset = 0;
  for (const entry of entries) {
    const name = encoder.encode(entry.path);
    const content = typeof entry.content === "string" ? encoder.encode(entry.content) : entry.content;
    const deflate = (entry.method ?? "deflate") === "deflate";
    const data = deflate ? await deflateRaw(content) : content;
    const size = entry.declaredSize ?? content.byteLength;
    const crc = crc32(content);
    const method = deflate ? 8 : 0;

    const local = new Uint8Array(30 + name.byteLength + data.byteLength);
    const lv = new DataView(local.buffer);
    lv.setUint32(0, 0x04034b50, true);
    lv.setUint16(4, 20, true);
    lv.setUint16(6, 0x0800, true);
    lv.setUint16(8, method, true);
    lv.setUint16(10, DOS_TIME, true);
    lv.setUint16(12, DOS_DATE, true);
    lv.setUint32(14, crc, true);
    lv.setUint32(18, data.byteLength, true);
    lv.setUint32(22, size, true);
    lv.setUint16(26, name.byteLength, true);
    local.set(name, 30);
    local.set(data, 30 + name.byteLength);

    const central = new Uint8Array(46 + name.byteLength);
    const cv = new DataView(central.buffer);
    cv.setUint32(0, 0x02014b50, true);
    cv.setUint16(4, UNIX_MADE_BY, true);
    cv.setUint16(6, 20, true);
    cv.setUint16(8, 0x0800, true);
    cv.setUint16(10, method, true);
    cv.setUint16(12, DOS_TIME, true);
    cv.setUint16(14, DOS_DATE, true);
    cv.setUint32(16, crc, true);
    cv.setUint32(20, data.byteLength, true);
    cv.setUint32(24, size, true);
    cv.setUint16(28, name.byteLength, true);
    const mode = entry.symlink ? 0o120777 : entry.path.endsWith("/") ? 0o040755 : 0o100644;
    cv.setUint32(38, (mode << 16) >>> 0, true);
    cv.setUint32(42, offset, true);
    central.set(name, 46);

    locals.push(local);
    centrals.push(central);
    offset += local.byteLength;
  }
  const centralSize = centrals.reduce((sum, c) => sum + c.byteLength, 0);
  const end = new Uint8Array(22);
  const ev = new DataView(end.buffer);
  ev.setUint32(0, 0x06054b50, true);
  ev.setUint16(8, entries.length, true);
  ev.setUint16(10, entries.length, true);
  ev.setUint32(12, centralSize, true);
  ev.setUint32(16, offset, true);

  const out = new Uint8Array(offset + centralSize + end.byteLength);
  let at = 0;
  for (const part of [...locals, ...centrals, end]) {
    out.set(part, at);
    at += part.byteLength;
  }
  return out;
}
