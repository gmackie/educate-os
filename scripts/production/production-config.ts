/** One long-lived instance: where it runs and the account resources its Workers bind. */
export interface ProductionInstance {
  /** The public hostname: the router's custom domain. Every other URL derives from it. */
  hostname: string;
  /** The Cloudflare account every Worker deploys to. */
  accountId: string;
  /** The gatekeeper packages deployed and bound; any other gatekeeper is left out. */
  gatekeepers: string[];
  /** KV namespace ids, by package and then binding. */
  kvNamespaces: Record<string, Record<string, string>>;
  /** R2 bucket names, by package and then binding. */
  r2Buckets: Record<string, Record<string, string>>;
  /** Plain-text vars added to a package's own, by package. Never secrets. */
  vars: Record<string, Record<string, string>>;
  /** The AI call guard. Its `AI_GUARD_CONFIG` is a secret the deployer delivers. */
  aiGuard: {
    /** The Worker the guard binds as `HALL_MONITOR`. */
    hallMonitorService: string;
  };
  /**
   * The district Worker, when the instance runs one. Its `DISTRICT_CONFIG` and Access pair are
   * secrets the deployer delivers. It has its own hostname, behind its own Access application,
   * because the router sends `/api/*` to the backend.
   */
  district?: {
    /** The district's public hostname: the district Worker's custom domain. */
    hostname: string;
    /**
     * More custom domains on the same Worker, such as its managed default hostname
     * `<slug>.educateos.io` (SCHO-207). They are routing only: the district's identity stays
     * `hostname`. The district's Access applications (the app and its `/healthz` bypass) must list
     * each one as a destination before it is deployed, or it would serve without Access.
     */
    aliases?: string[];
  };
  /**
   * One origin per district (ADR-0014): when `enabled`, the router serves the district at the root
   * of `hostname` (a `DISTRICT` service binding, `run_worker_first: true`), the Workshop under
   * `/ai`, and the instance's and the district's old hostnames answer with redirects to it
   * (`LEGACY_HOSTS`). The district Worker gets no hostname of its own. Off (or absent), nothing
   * changes.
   */
  oneOrigin?: {
    enabled: boolean;
    /** The district's one hostname, which the router takes over from the district Worker. */
    hostname: string;
  };
  /**
   * The Workshop backend's bindings to the district's `DistrictPrincipalResolver` (ADR-0003,
   * SCHO-259), one cutover step at a time: `migration` binds `PRINCIPAL_MIGRATION` only, for the
   * migration's dry run and apply, which changes no sign-in; `resolver` adds `PRINCIPAL_RESOLVER`, so
   * the Workshop keys sign-ins by principal. Absent, neither is bound.
   */
  principalBinding?: "migration" | "resolver";
  /**
   * Deployed Worker names that differ from their package's, by package. A deployed Worker's name
   * is production identity, like a hostname or a ForgeGraph app slug: a Durable Object namespace
   * belongs to its Worker's name, so deploying a stateful Worker under a new name starts it with
   * empty storage, and leaves the old Worker (and its custom domain) serving the real data. When a
   * package is renamed, the instance pins the Worker's old name here. The generator applies it to
   * the Worker's own `name` and to every service binding that reaches it.
   */
  workerNames?: Record<string, string>;
}

/** The name `pkgName`'s Worker is deployed under in `instance`: pinned, or its package name. */
export function productionWorkerName(instance: ProductionInstance, pkgName: string): string {
  return instance.workerNames?.[pkgName] ?? pkgName;
}

/** A KV namespace binding with its namespace id. */
interface KvNamespace {
  binding: string;
  id: string;
}

/** An R2 bucket binding with its bucket name. */
interface R2Bucket {
  binding: string;
  bucket_name: string;
}

/** A generated `wrangler.production.jsonc`. */
export interface ProductionConfig extends Omit<StagingConfig, "previews" | "routes" | "kv_namespaces" | "r2_buckets" | "assets"> {
  /** Static assets; a one-origin router runs first for every path (`run_worker_first: true`). */
  assets?: Omit<NonNullable<StagingConfig["assets"]>, "run_worker_first"> & { run_worker_first?: string[] | true };
  /** KV namespaces, with the instance's ids. */
  kv_namespaces?: KvNamespace[];
  /** R2 buckets, with the instance's bucket names. */
  r2_buckets?: R2Bucket[];
  /** The router's, or the district Worker's, custom domains. */
  routes?: { pattern: string; custom_domain: true }[];
}

type PackageConfig = Pick<DeployablePackage, "name" | "config">;

/**
 * The packages an instance deploys: router, backend, AI call guard, its gatekeepers and, if it has
 * one, the district Worker, sorted.
 */
export function productionPackageNames(instance: ProductionInstance): string[] {
  return ["router", "workshop-backend", AI_GUARD_PACKAGE, ...instance.gatekeepers,
    ...instance.district ? [DISTRICT_PACKAGE] : []].toSorted();
}

// Give each declared resource binding the instance's value, failing on a binding the instance does
// not name and on a value naming a binding the Worker does not declare.
function bindResources<T>(
  pkgName: string,
  kind: string,
  declared: readonly { binding: string }[] | undefined,
  values: Record<string, string> | undefined,
  make: (binding: string, value: string) => T,
): T[] | undefined {
  const known = values ?? {};
  const bindings = (declared ?? []).map(({ binding }) => {
    const value = known[binding];
    if (!value) {
      throw new Error(`${pkgName} declares ${kind} ${binding}, but the instance names no ` +
          `resource for it; add one in scripts/production/`);
    }
    return make(binding, value);
  });
  for (const binding of Object.keys(known)) {
    if (!bindings.some((entry) => (entry as { binding: string }).binding === binding)) {
      throw new Error(`the instance names ${kind} ${binding} for ${pkgName}, which declares no ` +
          `such binding`);
    }
  }
  return bindings.length > 0 ? bindings : undefined;
}

function withVars(
  pkgName: string,
  config: ProductionConfig,
  vars: Record<string, unknown>,
): void {
  config.vars = { ...config.vars, ...vars };
  for (const [name, value] of Object.entries(config.vars)) {
    if (SECRET_NAMES.has(name)) {
      throw new Error(`${pkgName} would get ${name} as a plain-text var; it is a secret, ` +
          "delivered by the deployer, and never belongs in a committed config");
    }
    if (typeof value === "string" && new TextEncoder().encode(value).byteLength > MAX_VAR_BYTES) {
      throw new Error(`${pkgName}'s ${name} is over Cloudflare's ${MAX_VAR_BYTES}-byte var limit`);
    }
  }
}

/**
 * Makes `config` (the district package's, already named and on its account) a deployed district:
 * its custom domains, its UIs as assets, and its LTI Tool at its first hostname, the district's
 * identity. Shared by an instance's district and the demo districts.
 */
function asDistrict(
  config: ProductionConfig,
  hostnames: readonly string[],
  vars: Record<string, string>,
  { routed = true, extraRoutes = [] }: { routed?: boolean; extraRoutes?: readonly string[] } = {},
): void {
  if ((config.triggers?.crons?.length ?? 0) < 2) {
    throw new Error(`${DISTRICT_PACKAGE}/wrangler.jsonc has lost its notification and digest Cron Triggers`);
  }
  if (config.assets) throw new Error(`${DISTRICT_PACKAGE}/wrangler.jsonc declares assets; the generator owns them`);
  if (config.services?.length) {
    throw new Error(`${DISTRICT_PACKAGE}/wrangler.jsonc binds another Worker; the generator cannot place it`);
  }
  // Wrangler replaces a Worker's custom domains with exactly these, so every alias is listed. Behind
  // a one-origin router the district has none: the router reaches it by service binding.
  if (routed) config.routes = hostnames.map((pattern) => ({ pattern, custom_domain: true as const }));
  config.assets = {
    directory: DISTRICT_UI_DIR,
    not_found_handling: "single-page-application",
    run_worker_first: [...DISTRICT_WORKER_ROUTES, ...extraRoutes],
  };
  // The LTI Tool (SCHO-177) is served at the district's own hostname, the origin its platform
  // registrations name.
  withVars(DISTRICT_PACKAGE, config, { LTI_TOOL_ORIGIN: `https://${hostnames[0]}`, ...vars });
}

