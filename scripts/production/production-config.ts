/** A demo district's Worker name: its own, so its own Durable Object namespace. */
export function demoDistrictWorkerName(slug: string): string {
  return `educateos-${slug}-district`;
}

/** A demo district's generated config file, in the district package (committed). */
export function demoDistrictConfigName(slug: string): string {
  return `wrangler.demo-${slug}.jsonc`;
}

/**
 * Build each demo district's config, by slug. Pure, like {@link buildProductionConfigs}: each is the
 * district package's wrangler.jsonc made a district Worker named for its slug, with only its own
 * hostname. Fails on a repeated slug or hostname, or one that clashes with `instance`'s district.
 */
export function buildDemoDistrictConfigs({
  districts,
  packages,
  instance,
}: {
  districts: readonly DemoDistrictDeployment[];
  packages: readonly PackageConfig[];
  instance?: ProductionInstance;
}): Map<string, ProductionConfig> {
  const pkg = packages.find((candidate) => candidate.name === DISTRICT_PACKAGE);
  if (!pkg) throw new Error(`${DISTRICT_PACKAGE} is no deployable package`);
  const taken = new Set(instance?.district ? [instance.district.hostname, ...instance.district.aliases ?? []] : []);
  const names = new Set(instance ? productionPackageNames(instance).map((name) => productionWorkerName(instance, name)) : []);
  const configs = new Map<string, ProductionConfig>();
  for (const district of districts) {
    if (!/^[a-z][a-z0-9-]{2,31}$/.test(district.slug)) throw new Error(`${district.slug} is not a district slug`);
    const name = demoDistrictWorkerName(district.slug);
    if (configs.has(district.slug) || names.has(name)) throw new Error(`two Workers would be deployed as ${name}`);
    if (taken.has(district.hostname)) throw new Error(`${district.hostname} is already another district's hostname`);
    taken.add(district.hostname);
    names.add(name);
    const { kv_namespaces, r2_buckets, d1_databases, routes: _routes, ...rest } = structuredClone(pkg.config) as StagingConfig;
    if (kv_namespaces?.length || r2_buckets?.length || d1_databases?.length) {
      throw new Error(`${DISTRICT_PACKAGE} declares account resources; a demo district would need its own`);
    }
    const config: ProductionConfig = {
      ...rest,
      name,
      account_id: district.accountId,
      workers_dev: false,
      preview_urls: false,
    };
    if (district.oneOrigin?.enabled) {
      // No router in front: the district answers /ai itself, so the Worker runs first for it.
      asDistrict(config, [district.hostname], {
        AI_DEMO_URL: district.oneOrigin.aiDemoUrl,
        SCHOOL_MANIFEST: schoolManifestVar(`https://${district.hostname}`, false),
      }, { extraRoutes: AI_DISABLED_ROUTES });
    } else {
      asDistrict(config, [district.hostname], {});
    }
    configs.set(district.slug, config);
  }
  return configs;
}

/**
 * Build every package's production config. Pure: `packages` are the parsed wrangler.jsonc files
 * (the instance's own subset is picked from them); the result maps package name to its config.
 */
export function buildProductionConfigs({
  instance,
  packages,
}: {
  instance: ProductionInstance;
  packages: readonly PackageConfig[];
}): Map<string, ProductionConfig> {
  const oneOrigin = instance.oneOrigin?.enabled ? oneOriginHosts(instance) : undefined;
  // On one origin every URL the instance hands out is on the district's hostname.
  const baseUrl = `https://${oneOrigin?.origin ?? instance.hostname}`;
  const gatekeepers = instance.gatekeepers.toSorted();
  for (const name of gatekeepers) {
    if (!isGatekeeperPackage(name)) throw new Error(`${name} is not a gatekeeper package`);
  }
  for (const pkgName of [...Object.keys(instance.kvNamespaces), ...Object.keys(instance.r2Buckets),
    ...Object.keys(instance.vars)]) {
    if (!productionPackageNames(instance).includes(pkgName)) {
      throw new Error(`the instance configures ${pkgName}, which it does not deploy`);
    }
  }
  const packageNames = productionPackageNames(instance);
  for (const pkgName of Object.keys(instance.workerNames ?? {})) {
    if (!packageNames.includes(pkgName)) {
      throw new Error(`the instance pins a Worker name for ${pkgName}, which it does not deploy`);
    }
  }
  const workerNames = packageNames.map((pkgName) => productionWorkerName(instance, pkgName));
  const duplicate = workerNames.find((name, index) => workerNames.indexOf(name) !== index);
  if (duplicate) throw new Error(`two of the instance's Workers would be deployed as ${duplicate}`);

  const configs = new Map<string, ProductionConfig>();
  for (const pkgName of productionPackageNames(instance)) {
    const pkg = packages.find((candidate) => candidate.name === pkgName);
    if (!pkg) throw new Error(`the instance deploys ${pkgName}, which is no deployable package`);
    const source = structuredClone(pkg.config) as StagingConfig;
    if (source.name !== pkgName) {
      // Every service binding names its target by package name.
      throw new Error(`${pkgName}/wrangler.jsonc declares worker name "${source.name}"; the ` +
          "production generator requires them to match");
    }
    if (source.d1_databases?.length) {
      throw new Error(`${pkgName} declares D1 databases; production-config.ts does not bind D1 yet`);
    }
    const { kv_namespaces, r2_buckets, routes: _routes, ...rest } = source;
    const config: ProductionConfig = {
      ...rest,
      name: productionWorkerName(instance, pkgName),
      account_id: instance.accountId,
      // Only the router is reachable, and only at its custom domain: everything else is reached
      // through it over service bindings. Stated explicitly, as staging-config.ts does, so neither
      // depends on a default or on what the dashboard was last toggled to.
      workers_dev: false,
      preview_urls: false,
    };
    const kv = bindResources(pkgName, "KV namespace", kv_namespaces, instance.kvNamespaces[pkgName],
        (binding, id) => ({ binding, id }));
    if (kv) config.kv_namespaces = kv;
    const r2 = bindResources(pkgName, "R2 bucket", r2_buckets, instance.r2Buckets[pkgName],
        (binding, bucket_name) => ({ binding, bucket_name }));
    if (r2) config.r2_buckets = r2;

    const vars = instance.vars[pkgName] ?? {};
    if (isGatekeeperPackage(pkgName)) {
      if (pkgName === EDUCATEOS_GATEKEEPER_PACKAGE) {
        // Its district binding is injected by the deployment (see its README); without one the
        // connector refuses every call, so an instance with no district cannot install it.
        if (!instance.district) {
          throw new Error(`${pkgName} needs the instance's district Worker, which this instance does not run`);
        }
        config.services = [...config.services ?? [], EDUCATEOS_DISTRICT_BINDING];
      }
      // The School app's links that leave it (a calendar feed) name the district's own address.
      const district = pkgName === EDUCATEOS_GATEKEEPER_PACKAGE
        ? { DISTRICT_URL: oneOrigin ? baseUrl : `https://${instance.district!.hostname}` }
        : {};
      withVars(pkgName, config, { BASE_URL: gatekeeperBaseUrl(baseUrl, pkgName), ...district, ...vars });
    } else if (pkgName === "workshop-backend") {
      if (config.ai) {
        throw new Error(`${pkgName} declares an ai binding, but WORKERS_AI is injected here (as ` +
            "manifest-lib.ts does); declaring it too would bind it twice");
      }
      config.ai = { binding: "WORKERS_AI" };
      config.services = [...backendGatekeeperServices(gatekeepers, baseUrl), backendAiGuardBinding(), ...principalServices(instance)];
      withVars(pkgName, config, { PUBLIC_BASE_URL: baseUrl, ...oneOrigin ? { PUBLIC_BASE_PATH: ONE_ORIGIN_BASE_PATH } : {}, ...vars });
    } else if (pkgName === "router") {
      config.services = routerServices(gatekeepers);
      config.routes = [{ pattern: instance.hostname, custom_domain: true }];
      if (oneOrigin) {
        // ADR-0014: the router owns the district's hostname, and keeps the old ones to redirect.
        config.services.push({ binding: "DISTRICT", service: DISTRICT_PACKAGE });
        config.routes = [oneOrigin.origin, ...oneOrigin.legacy.keys()].map((pattern) => ({ pattern, custom_domain: true as const }));
        if (!config.assets) throw new Error(`${pkgName}/wrangler.jsonc serves no assets; a one-origin router serves the Workshop's`);
        config.assets = { ...config.assets, run_worker_first: true };
        withVars(pkgName, config, { LEGACY_HOSTS: JSON.stringify(Object.fromEntries(oneOrigin.legacy)), ...vars });
      } else {
        withVars(pkgName, config, vars);
      }
    } else if (pkgName === AI_GUARD_PACKAGE) {
      if (config.main === AI_GUARD_DEV_MAIN) {
        throw new Error(`${pkgName}/wrangler.jsonc names the development entrypoint`);
      }
      if (!config.triggers?.crons?.length) {
        throw new Error(`${pkgName}/wrangler.jsonc has lost its nightly reconciliation Cron Trigger`);
      }
      // Preferred by the guard over HALL_MONITOR_URL (src/hall-monitor.ts), so that var is not set.
      const hallMonitor: ServiceBinding =
          { binding: "HALL_MONITOR", service: instance.aiGuard.hallMonitorService };
      config.services = [...config.services ?? [], hallMonitor, ...instance.district ? [GUARD_DISTRICT_BINDING] : []];
      withVars(pkgName, config, vars);
    } else if (pkgName === DISTRICT_PACKAGE && instance.district) {
      const hostnames = [instance.district.hostname, ...instance.district.aliases ?? []];
      if (oneOrigin) {
        // Behind the router, at no hostname of its own. Its LTI Tool keeps the origin platforms
        // registered, which the router redirects to the one origin with method and body kept.
        asDistrict(config, hostnames, { SCHOOL_MANIFEST: schoolManifestVar(baseUrl, true, ONE_ORIGIN_PHONE_SIGN_IN), ...vars }, { routed: false });
      } else {
        asDistrict(config, hostnames, vars);
      }
    } else {
      throw new Error(`cannot build a production config for package: ${pkgName}`);
    }
    configs.set(pkgName, config);
  }

  // Every binding above names its target by package name; point each at the name that package's
  // Worker is deployed under. Anything else must be a Worker the instance knows is already there.
  const external = new Set([instance.aiGuard.hallMonitorService]);
  for (const [pkgName, config] of configs) {
    if (!config.services) continue;
    config.services = config.services.map((binding) => {
      if (packageNames.includes(binding.service)) {
        return { ...binding, service: productionWorkerName(instance, binding.service) };
      }
      if (external.has(binding.service)) return binding;
      throw new Error(`${pkgName}'s ${binding.binding} binds ${binding.service}, which is neither a ` +
          "Worker the instance deploys nor one it names as already deployed");
    });
  }
  return configs;
}

/** The district principal resolver's entrypoint, which only the Workshop backend may bind. */
export const PRINCIPAL_RESOLVER_ENTRYPOINT = "DistrictPrincipalResolver";

/** A backend binding named `binding` to the district's principal resolver. */
function principalBindingTo(binding: string): ServiceBinding {
  return { binding, service: DISTRICT_PACKAGE, entrypoint: PRINCIPAL_RESOLVER_ENTRYPOINT };
}

/** The backend's principal bindings for {@link ProductionInstance.principalBinding}. */
function principalServices(instance: ProductionInstance): ServiceBinding[] {
  if (!instance.principalBinding) return [];
  if (!instance.district) throw new Error("principal bindings need the instance's district Worker");
  return instance.principalBinding === "resolver"
    ? [principalBindingTo("PRINCIPAL_MIGRATION"), principalBindingTo("PRINCIPAL_RESOLVER")]
    : [principalBindingTo("PRINCIPAL_MIGRATION")];
}

/**
 * A one-origin instance's hostnames: its one origin, and every old hostname with the URL prefix it
 * now redirects to, the instance's (the Workshop's, so under /ai) and the district's (the LMS's,
 * so the root). Fails on an instance that cannot have one origin.
 */
function oneOriginHosts(instance: ProductionInstance): { origin: string; legacy: Map<string, string> } {
  const origin = instance.oneOrigin!.hostname;
  if (!instance.district) throw new Error("a one-origin instance needs a district Worker for the router to front");
  if (origin === instance.hostname) throw new Error(`${origin} is the instance's old hostname; one origin needs the district's`);
  const base = `https://${origin}`;
  const legacy = new Map<string, string>([[instance.hostname, `${base}${ONE_ORIGIN_BASE_PATH}`]]);
  for (const host of [instance.district.hostname, ...instance.district.aliases ?? []]) {
    if (host !== origin) legacy.set(host, base);
  }
  return { origin, legacy };
}

/**
 * Build env each package's deploy build must set, by package: a one-origin router's frontend is
 * built for /ai. Empty for every other instance. The deployer's build command carries it (the
 * router's `buildCommand` in .forgegraph.yaml), since a Wrangler config cannot.
 */
export function productionBuildEnv(instance: ProductionInstance): Record<string, Record<string, string>> {
  return instance.oneOrigin?.enabled ? { router: { ...ONE_ORIGIN_BUILD_ENV } } : {};
}

/** A generated config file's text. */
export function renderProductionConfig(config: ProductionConfig): string {
  return HEADER + JSON.stringify(config, null, 2) + "\n";
}

/**
 * Regenerate every production config, the instance's and the demo districts', writing only files
 * whose content changed. With `check`, writes nothing. Returns the repo-relative paths that differed.
 */
export function generateProductionConfigs({
  check,
  instance = SCHOOLOS_GMAC_IO,
  districts = DEMO_DISTRICT_DEPLOYMENTS,
}: {
  check: boolean;
  instance?: ProductionInstance;
  districts?: readonly DemoDistrictDeployment[];
}): string[] {
  const packages = readDeployablePackages(PACKAGES_DIR);
  const dir = (pkgName: string) => packages.find((candidate) => candidate.name === pkgName)!.dir;
  const files: [string, ProductionConfig][] = [
    ...[...buildProductionConfigs({ instance, packages })]
      .map(([pkgName, config]): [string, ProductionConfig] => [join(dir(pkgName), PRODUCTION_CONFIG_NAME), config]),
    ...[...buildDemoDistrictConfigs({ districts, packages, instance })]
      .map(([slug, config]): [string, ProductionConfig] => [join(dir(DISTRICT_PACKAGE), demoDistrictConfigName(slug)), config]),
  ];
  return files.flatMap(([path, config]) => {
    const text = renderProductionConfig(config);
    if (existsSync(path) && readFileSync(path, "utf8") === text) return [];
    const rel = relative(ROOT, path);
    if (!check) {
      writeFileSync(path, text);
      console.log(`gen ${rel}`);
    }
    return [rel];
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const stale = generateProductionConfigs({ check });
  if (check && stale.length > 0) {
    console.error("production configs out of date (run `pnpm production:configs`):\n  " +
        stale.join("\n  "));
    process.exitCode = 1;
  }
}
