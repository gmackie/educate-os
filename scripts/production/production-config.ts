#!/usr/bin/env node

// Generates a committed `wrangler.production.jsonc` beside the wrangler.jsonc of each Worker in a
// long-lived production instance (today one: schoolos.gmac.io, see schoolos-gmac-io.ts), so a
// deployer that runs plain `wrangler deploy -c wrangler.production.jsonc` from the package
// directory (ForgeGraph does) deploys it as the instance needs.
//
// This is the PR-preview generator's *baseline* half (scripts/preview/staging-config.ts) pointed at
// real resources: the same worker names (= package names) and the same service-binding topology,
// built from the same helpers, but with
//   - the instance's real KV namespace ids and R2 bucket names, where a preview baseline strips
//     them to have Wrangler provision throwaway ones. Every resource binding a Worker declares
//     must be named here, and nothing else may be, so a new binding fails the generator rather than
//     deploying unbound;
//   - one public hostname, the router's custom domain, and no workers.dev or preview URLs at all;
//   - only the gatekeepers the instance lists, bound to the router and the backend;
//   - the AI call guard's production entrypoint, its nightly Cron Trigger and a `HALL_MONITOR`
//     service binding to the account's Hall Monitor Worker, where a preview runs the development
//     entrypoint with an in-process fake and no cron;
//   - when the instance has a district, the district Worker (SCHO-193) at its own custom domain,
//     serving the district's `/api` and, as static assets, the student, admin and teacher UIs
//     (assembled by assemble-district-ui.ts at deploy time);
//   - no `previews` blocks.
//
// Secrets are never part of a generated config (Wrangler prints vars, and these files are
// committed): a var with a secret's name fails the generator.
//
// Usage: node scripts/production/production-config.ts [--check]

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { AI_GUARD_DEV_MAIN, AI_GUARD_PACKAGE, backendAiGuardBinding } from "../ai-guard-dev.ts";
import {
  isGatekeeperPackage, readDeployablePackages, type DeployablePackage, type ServiceBinding,
} from "../release/manifest-lib.ts";
import {
  PACKAGES_DIR, ROOT, backendGatekeeperServices, gatekeeperBaseUrl, routerServices,
  type StagingConfig,
} from "../preview/staging-config.ts";
import { SCHOOLOS_GMAC_IO } from "./schoolos-gmac-io.ts";

/** The generated per-package config file name (committed). */
export const PRODUCTION_CONFIG_NAME = "wrangler.production.jsonc";

const HEADER =
  "// Generated by scripts/production/production-config.ts -- do not edit.\n" +
  "// Change scripts/production/ (or the package's cloudflare.config.ts) and run " +
  "`pnpm production:configs`.\n";

/** Cloudflare's limit on one plain-text var. */
export const MAX_VAR_BYTES = 5000;

/**
 * Names that are secrets in some Worker of the instance. ForgeGraph delivers them; a plain-text var
 * of the same name would be printed by Wrangler, committed here, and would shadow nothing (a
 * secret and a var cannot share a name), so it is refused.
 */
const SECRET_NAMES = new Set([
  "ADMINS", "AI_GUARD_CONFIG", "CF_ACCESS_AUD", "CF_ACCESS_ISS", "CF_AI_GATEWAY_API_TOKEN", "HALL_MONITOR_SIGNING_KEY",
  "AI_GATEWAY_LOGS_TOKEN", "CLIENT_ID", "CLIENT_SECRET", "DISTRICT_CONFIG",
]);

/** The district Worker's package (and worker) name. */
export const DISTRICT_PACKAGE = "educateos-district-worker";

/**
 * Where the district Worker's static assets are, relative to its package: the three UIs as
 * assemble-district-ui.ts lays them out (student at `/`, admin at `/admin/`, teacher at `/teach/`).
 */
export const DISTRICT_UI_DIR = "./dist/ui";

/** The district Worker's own routes, which run before its assets: the API and the liveness probe. */
export const DISTRICT_WORKER_ROUTES = ["/api/*", "/healthz"];

/** One long-lived instance: where it runs and the account resources its Workers bind. */
export interface ProductionInstance {
  /** The public hostname: the router's custom domain. Every other URL derives from it. */
  hostname: string;
  /** The Cloudflare account every Worker deploys to. */
  accountId: string;
  /** The gatekeeper packages deployed and bound; any other gatekeeper is left out. */
  gatekeepers: string[];
  /** KV namespace ids, by package and then binding. */
  kvNamespaces: Record<string, Record<string, string>>;
  /** R2 bucket names, by package and then binding. */
  r2Buckets: Record<string, Record<string, string>>;
  /** Plain-text vars added to a package's own, by package. Never secrets. */
  vars: Record<string, Record<string, string>>;
  /** The AI call guard. Its `AI_GUARD_CONFIG` is a secret the deployer delivers. */
  aiGuard: {
    /** The Worker the guard binds as `HALL_MONITOR`. */
    hallMonitorService: string;
  };
  /**
   * The district Worker, when the instance runs one. Its `DISTRICT_CONFIG` and Access pair are
   * secrets the deployer delivers. It has its own hostname, behind its own Access application,
   * because the router sends `/api/*` to the backend.
   */
  district?: {
    /** The district's public hostname: the district Worker's custom domain. */
    hostname: string;
  };
}

/** A KV namespace binding with its namespace id. */
interface KvNamespace {
  binding: string;
  id: string;
}

/** An R2 bucket binding with its bucket name. */
interface R2Bucket {
  binding: string;
  bucket_name: string;
}

/** A generated `wrangler.production.jsonc`. */
export interface ProductionConfig extends Omit<StagingConfig, "previews" | "routes" | "kv_namespaces" | "r2_buckets"> {
  /** KV namespaces, with the instance's ids. */
  kv_namespaces?: KvNamespace[];
  /** R2 buckets, with the instance's bucket names. */
  r2_buckets?: R2Bucket[];
  /** The router's, or the district Worker's, custom domain. */
  routes?: { pattern: string; custom_domain: true }[];
}

type PackageConfig = Pick<DeployablePackage, "name" | "config">;

/**
 * The packages an instance deploys: router, backend, AI call guard, its gatekeepers and, if it has
 * one, the district Worker, sorted.
 */
export function productionPackageNames(instance: ProductionInstance): string[] {
  return ["router", "workshop-backend", AI_GUARD_PACKAGE, ...instance.gatekeepers,
    ...instance.district ? [DISTRICT_PACKAGE] : []].toSorted();
}

// Give each declared resource binding the instance's value, failing on a binding the instance does
// not name and on a value naming a binding the Worker does not declare.
function bindResources<T>(
  pkgName: string,
  kind: string,
  declared: readonly { binding: string }[] | undefined,
  values: Record<string, string> | undefined,
  make: (binding: string, value: string) => T,
): T[] | undefined {
  const known = values ?? {};
  const bindings = (declared ?? []).map(({ binding }) => {
    const value = known[binding];
    if (!value) {
      throw new Error(`${pkgName} declares ${kind} ${binding}, but the instance names no ` +
          `resource for it; add one in scripts/production/`);
    }
    return make(binding, value);
  });
  for (const binding of Object.keys(known)) {
    if (!bindings.some((entry) => (entry as { binding: string }).binding === binding)) {
      throw new Error(`the instance names ${kind} ${binding} for ${pkgName}, which declares no ` +
          `such binding`);
    }
  }
  return bindings.length > 0 ? bindings : undefined;
}

function withVars(
  pkgName: string,
  config: ProductionConfig,
  vars: Record<string, unknown>,
): void {
  config.vars = { ...config.vars, ...vars };
  for (const [name, value] of Object.entries(config.vars)) {
    if (SECRET_NAMES.has(name)) {
      throw new Error(`${pkgName} would get ${name} as a plain-text var; it is a secret, ` +
          "delivered by the deployer, and never belongs in a committed config");
    }
    if (typeof value === "string" && new TextEncoder().encode(value).byteLength > MAX_VAR_BYTES) {
      throw new Error(`${pkgName}'s ${name} is over Cloudflare's ${MAX_VAR_BYTES}-byte var limit`);
    }
  }
}

/**
 * Build every package's production config. Pure: `packages` are the parsed wrangler.jsonc files
 * (the instance's own subset is picked from them); the result maps package name to its config.
 */
export function buildProductionConfigs({
  instance,
  packages,
}: {
  instance: ProductionInstance;
  packages: readonly PackageConfig[];
}): Map<string, ProductionConfig> {
  const baseUrl = `https://${instance.hostname}`;
  const gatekeepers = instance.gatekeepers.toSorted();
  for (const name of gatekeepers) {
    if (!isGatekeeperPackage(name)) throw new Error(`${name} is not a gatekeeper package`);
  }
  for (const pkgName of [...Object.keys(instance.kvNamespaces), ...Object.keys(instance.r2Buckets),
    ...Object.keys(instance.vars)]) {
    if (!productionPackageNames(instance).includes(pkgName)) {
      throw new Error(`the instance configures ${pkgName}, which it does not deploy`);
    }
  }

  const configs = new Map<string, ProductionConfig>();
  for (const pkgName of productionPackageNames(instance)) {
    const pkg = packages.find((candidate) => candidate.name === pkgName);
    if (!pkg) throw new Error(`the instance deploys ${pkgName}, which is no deployable package`);
    const source = structuredClone(pkg.config) as StagingConfig;
    if (source.name !== pkgName) {
      // Every service binding names its target by package name.
      throw new Error(`${pkgName}/wrangler.jsonc declares worker name "${source.name}"; the ` +
          "production generator requires them to match");
    }
    if (source.d1_databases?.length) {
      throw new Error(`${pkgName} declares D1 databases; production-config.ts does not bind D1 yet`);
    }
    const { kv_namespaces, r2_buckets, routes: _routes, ...rest } = source;
    const config: ProductionConfig = {
      ...rest,
      name: pkgName,
      account_id: instance.accountId,
      // Only the router is reachable, and only at its custom domain: everything else is reached
      // through it over service bindings. Stated explicitly, as staging-config.ts does, so neither
      // depends on a default or on what the dashboard was last toggled to.
      workers_dev: false,
      preview_urls: false,
    };
    const kv = bindResources(pkgName, "KV namespace", kv_namespaces, instance.kvNamespaces[pkgName],
        (binding, id) => ({ binding, id }));
    if (kv) config.kv_namespaces = kv;
    const r2 = bindResources(pkgName, "R2 bucket", r2_buckets, instance.r2Buckets[pkgName],
        (binding, bucket_name) => ({ binding, bucket_name }));
    if (r2) config.r2_buckets = r2;

    const vars = instance.vars[pkgName] ?? {};
    if (isGatekeeperPackage(pkgName)) {
      withVars(pkgName, config, { BASE_URL: gatekeeperBaseUrl(baseUrl, pkgName), ...vars });
    } else if (pkgName === "workshop-backend") {
      if (config.ai) {
        throw new Error(`${pkgName} declares an ai binding, but WORKERS_AI is injected here (as ` +
            "manifest-lib.ts does); declaring it too would bind it twice");
      }
      config.ai = { binding: "WORKERS_AI" };
      config.services = [...backendGatekeeperServices(gatekeepers, baseUrl), backendAiGuardBinding()];
      withVars(pkgName, config, { PUBLIC_BASE_URL: baseUrl, ...vars });
    } else if (pkgName === "router") {
      config.services = routerServices(gatekeepers);
      config.routes = [{ pattern: instance.hostname, custom_domain: true }];
      withVars(pkgName, config, vars);
    } else if (pkgName === AI_GUARD_PACKAGE) {
      if (config.main === AI_GUARD_DEV_MAIN) {
        throw new Error(`${pkgName}/wrangler.jsonc names the development entrypoint`);
      }
      if (!config.triggers?.crons?.length) {
        throw new Error(`${pkgName}/wrangler.jsonc has lost its nightly reconciliation Cron Trigger`);
      }
      // Preferred by the guard over HALL_MONITOR_URL (src/hall-monitor.ts), so that var is not set.
      const hallMonitor: ServiceBinding =
          { binding: "HALL_MONITOR", service: instance.aiGuard.hallMonitorService };
      config.services = [...config.services ?? [], hallMonitor];
      withVars(pkgName, config, vars);
    } else if (pkgName === DISTRICT_PACKAGE && instance.district) {
      if ((config.triggers?.crons?.length ?? 0) < 2) {
        throw new Error(`${pkgName}/wrangler.jsonc has lost its notification and digest Cron Triggers`);
      }
      if (config.assets) throw new Error(`${pkgName}/wrangler.jsonc declares assets; the generator owns them`);
      config.routes = [{ pattern: instance.district.hostname, custom_domain: true }];
      config.assets = {
        directory: DISTRICT_UI_DIR,
        not_found_handling: "single-page-application",
        run_worker_first: DISTRICT_WORKER_ROUTES,
      };
      withVars(pkgName, config, vars);
    } else {
      throw new Error(`cannot build a production config for package: ${pkgName}`);
    }
    configs.set(pkgName, config);
  }
  return configs;
}

/** A generated config file's text. */
export function renderProductionConfig(config: ProductionConfig): string {
  return HEADER + JSON.stringify(config, null, 2) + "\n";
}

/**
 * Regenerate every production config, writing only files whose content changed. With `check`,
 * writes nothing. Returns the repo-relative paths that differed.
 */
export function generateProductionConfigs(
  { check, instance = SCHOOLOS_GMAC_IO }: { check: boolean; instance?: ProductionInstance },
): string[] {
  const packages = readDeployablePackages(PACKAGES_DIR);
  const configs = buildProductionConfigs({ instance, packages });
  return [...configs].flatMap(([pkgName, config]) => {
    const pkg = packages.find((candidate) => candidate.name === pkgName)!;
    const path = join(pkg.dir, PRODUCTION_CONFIG_NAME);
    const text = renderProductionConfig(config);
    if (existsSync(path) && readFileSync(path, "utf8") === text) return [];
    const rel = relative(ROOT, path);
    if (!check) {
      writeFileSync(path, text);
      console.log(`gen ${rel}`);
    }
    return [rel];
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const stale = generateProductionConfigs({ check });
  if (check && stale.length > 0) {
    console.error("production configs out of date (run `pnpm production:configs`):\n  " +
        stale.join("\n  "));
    process.exitCode = 1;
  }
}
