// Generates the showcase's spoken recordings (SCHO-328): what each K-2 child says on a speaking step
// of the Northfield showcase, spoken by macOS `say` and kept as small 8 kHz 8-bit mono WAVs in
// packages/educateos-fixtures/src/showcase/recordings.ts, so the seeder hands in speech rather than
// a hummed tune. Run it once on a Mac after changing a line below:
//
//   node scripts/demo/spoken-recordings.ts
//
// The output is committed; nothing runs this in CI, and the seeder needs no `say` to use it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const OUT = new URL("../../packages/educateos-fixtures/src/showcase/recordings.ts", import.meta.url);
const SAMPLE_RATE = 8_000;
/** A clip may be no bigger than this, so the seeded showcase stays light in every bundle. */
const MAX_BYTES = 60_000;

const GIRL = "Flo (English (US))";
const BOY = "Junior";

/** Each spoken step, by the seeder's `studentId:activityKey:stepId`, with its line and voice. */
const LINES: readonly { key: string; voice: string; text: string }[] = [
  { key: "prn_nf-student-sofia:weather-chart:tell", voice: GIRL, text: "Today it is sunny. I see the sun, and one white cloud in the sky." },
  { key: "prn_nf-student-noah:weather-chart:tell", voice: BOY, text: "Today it is rainy. Lots and lots of rain!" },
  { key: "prn_nf-student-sofia:dress-for-weather:tell", voice: GIRL, text: "I wear my yellow boots, and my rain coat. I hold an umbrella." },
  { key: "prn_nf-student-noah:dress-for-weather:tell", voice: BOY, text: "Boots. Coat. And my hat with a dinosaur!" },
  { key: "prn_nf-student-priya:retell-seed:question-1", voice: GIRL, text: "First, the rain gave the seed a drink." },
  { key: "prn_nf-student-priya:retell-seed:question-2", voice: GIRL, text: "Next, the sun kept it warm." },
  { key: "prn_nf-student-jonah:retell-seed:question-1", voice: BOY, text: "First, the seed fell in the dirt." },
  { key: "prn_nf-student-jonah:retell-seed:question-2", voice: BOY, text: "Next, it rained." },
];

/** A WAV's `fmt ` and `data` chunks, rewritten with the canonical 44-byte header and nothing else. */
function canonicalWav(file: Uint8Array): Uint8Array {
  const view = new DataView(file.buffer, file.byteOffset, file.byteLength);
  const tag = (at: number) => String.fromCharCode(...file.subarray(at, at + 4));
  let format: Uint8Array | undefined;
  let data: Uint8Array | undefined;
  for (let at = 12; at + 8 <= file.length;) {
    const size = view.getUint32(at + 4, true);
    if (tag(at) === "fmt ") format = file.subarray(at + 8, at + 8 + 16);
    if (tag(at) === "data") data = file.subarray(at + 8, at + 8 + size);
    at += 8 + size + (size & 1);
  }
  if (format === undefined || data === undefined) throw new Error("afconvert wrote a WAV without fmt and data chunks");
  const out = new Uint8Array(44 + data.length);
  const header = new DataView(out.buffer);
  out.set(Buffer.from("RIFF"), 0);
  header.setUint32(4, 36 + data.length, true);
  out.set(Buffer.from("WAVEfmt "), 8);
  header.setUint32(16, 16, true);
  out.set(format, 20);
  out.set(Buffer.from("data"), 36);
  header.setUint32(40, data.length, true);
  out.set(data, 44);
  return out;
}

const work = mkdtempSync(join(tmpdir(), "spoken-recordings-"));
try {
  const entries = LINES.map(({ key, voice, text }, index) => {
    const aiff = join(work, `${index}.aiff`);
    const wav = join(work, `${index}.wav`);
    execFileSync("say", ["-v", voice, "-r", "150", "-o", aiff, text]);
    execFileSync("afconvert", ["-f", "WAVE", "-d", `UI8@${SAMPLE_RATE}`, "-c", "1", aiff, wav]);
    const clip = canonicalWav(readFileSync(wav));
    if (clip.length > MAX_BYTES) throw new Error(`${key} is ${clip.length} bytes; shorten its line`);
    return `  ${JSON.stringify(key)}:\n    ${JSON.stringify(Buffer.from(clip).toString("base64"))},`;
  });
  writeFileSync(OUT, [
    "// Generated by scripts/demo/spoken-recordings.ts with macOS `say` (SCHO-328). Do not edit by hand.",
    "",
    "/**",
    " * What each K-2 child of the showcase says on a speaking step, as 8 kHz 8-bit mono WAVs in base64,",
    " * by `studentId:activityKey:stepId`. Synthetic voices reading the child's scripted words.",
    " */",
    "export const SPOKEN_RECORDINGS: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n"));
  console.log(`Wrote ${LINES.length} clips to ${OUT.pathname}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
